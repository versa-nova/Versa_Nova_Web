// Current language
let currentLanguage = 'de';

// Change language function
function changeLanguage(lang) {
    currentLanguage = lang;
    localStorage.setItem('preferredLanguage', lang);
    
    // Update current language indicator
    document.getElementById('currentLang').textContent = lang.toUpperCase();
    
    // Update all translatable elements
    document.querySelectorAll('[data-translate]').forEach(element => {
        const key = element.getAttribute('data-translate');
        if (translations[lang][key]) {
            element.innerHTML = translations[lang][key];
        }
    });
    
    // Update placeholder attributes
    document.querySelectorAll('[data-translate-placeholder]').forEach(element => {
        const key = element.getAttribute('data-translate-placeholder');
        if (translations[lang][key]) {
            element.setAttribute('placeholder', translations[lang][key]);
        }
    });
    
    // Update hero text animation
    if (window.heroTexts && lang === 'de') {
        window.heroTexts = [
            'Wir entwickeln <span class="text-gradient">digitale Produkte</span> und interaktive Erlebnisse.',
            'Von <span class="text-gradient">der Idee bis zum Launch</span> entwickeln wir echte Produkte.',
            'Wir verbinden <span class="text-gradient">Apps, KI, Publishing und Games</span>.',
            'Technologie, Design und Kreativität – <span class="text-gradient">in Produkte verwandelt.</span>'
        ];
        const textElement = document.querySelector('.hero-text-animated');
        if (textElement) textElement.innerHTML = window.heroTexts[0];
    } else if (window.heroTexts && lang === 'en') {
        window.heroTexts = [
            'We build <span class="text-gradient">digital products</span> and interactive experiences.',
            'From <span class="text-gradient">concept to launch</span>, we turn ideas into real products.',
            'Building across <span class="text-gradient">apps, AI, publishing and games</span>.',
            'Technology, design and creativity — <span class="text-gradient">built into products.</span>'
        ];
        const textElement = document.querySelector('.hero-text-animated');
        if (textElement) textElement.innerHTML = window.heroTexts[0];
    }

    // Reinitialize AOS
    if (typeof AOS !== 'undefined') {
        AOS.refresh();
    }
}

// Initialize language on page load
document.addEventListener('DOMContentLoaded', function() {
    const savedLang = localStorage.getItem('preferredLanguage') || 'de';
    changeLanguage(savedLang);
});
